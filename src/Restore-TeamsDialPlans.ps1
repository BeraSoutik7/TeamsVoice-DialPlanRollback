<#
================================================================================
SCRIPT NAME : Restore-TeamsDialPlans.ps1
DESCRIPTION : Instant disaster-recovery rollback engine. Reverts Microsoft Teams
              Tenant Dial Plans, Normalization Rules, and user assignments back
              to an exact pre-change JSON backup snapshot within seconds.
AUTHOR      : Soutik Bera
REPOSITORY  : TeamsVoice-DialPlanRollback
MODULES REQ : MicrosoftTeams (v4.0.0+)
================================================================================
#>

[CmdletBinding(SupportsShouldProcess = $true, ConfirmImpact = 'High')]
param (
    [Parameter(Mandatory = $true, HelpMessage = "Path to the JSON backup file generated by Backup-TeamsDialPlans.ps1")]
    [ValidateScript({ Test-Path $_ -PathType Leaf })]
    [string]$BackupFilePath,

    [Parameter(Mandatory = $false, HelpMessage = "Optional: Restore only a specific Dial Plan by Identity/Name")]
    [string]$TargetDialPlanName,

    [Parameter(Mandatory = $false, HelpMessage = "Also restore explicit user TenantDialPlan assignments if present in backup")]
    [switch]$RestoreUserAssignments,

    [Parameter(Mandatory = $false, HelpMessage = "Skip confirmation prompts for emergency instant rollback")]
    [switch]$Force
)

$ErrorActionPreference = 'Stop'

if ($Force) {
    $ConfirmPreference = 'None'
}

# ------------------------------------------------------------------------------
# STEP 1: LOAD & VALIDATE BACKUP FILE
# ------------------------------------------------------------------------------
Write-Host "[*] Loading backup file: $BackupFilePath" -ForegroundColor Cyan
$BackupData = Get-Content -Path $BackupFilePath -Raw -Encoding utf8 | ConvertFrom-Json

if (-not $BackupData.Metadata -or -not $BackupData.DialPlans) {
    throw "Invalid backup file schema. Ensure the file was created by Backup-TeamsDialPlans.ps1."
}

Write-Host "[+] Backup Metadata Verified:" -ForegroundColor Green
Write-Host "    - Timestamp   : $($BackupData.Metadata.BackupTimestamp)"
Write-Host "    - Source Tenant: $($BackupData.Metadata.TenantName) ($($BackupData.Metadata.TenantId))"
Write-Host "    - Dial Plans  : $($BackupData.Metadata.TotalDialPlans)"

# ------------------------------------------------------------------------------
# STEP 2: AUTHENTICATE & VERIFY TENANT SAFETY GUARD
# ------------------------------------------------------------------------------
try {
    $currentTenant = Get-CsTenant -ErrorAction Stop
} catch {
    Connect-MicrosoftTeams
    $currentTenant = Get-CsTenant
}

if ($currentTenant.TenantId -ne $BackupData.Metadata.TenantId) {
    throw "CRITICAL SAFETY ABORT: Connected Tenant ID ($($currentTenant.TenantId)) does NOT match Backup Tenant ID ($($BackupData.Metadata.TenantId))!"
}

# ------------------------------------------------------------------------------
# STEP 3: ROLLBACK DIAL PLANS & NORMALIZATION RULES
# ------------------------------------------------------------------------------
$PlansToRestore = $BackupData.DialPlans
if ($TargetDialPlanName) {
    $PlansToRestore = $PlansToRestore | Where-Object {
        $_.Identity -eq $TargetDialPlanName -or $_.SimpleName -eq $TargetDialPlanName
    }
    if (-not $PlansToRestore) {
        throw "Dial Plan '$TargetDialPlanName' was not found inside the backup file."
    }
}

$Stopwatch = [System.Diagnostics.Stopwatch]::StartNew()
Write-Host "`n[*] Initiating Dial Plan Rollback..." -ForegroundColor Yellow

foreach ($plan in $PlansToRestore) {
    # Skip built-in read-only Global default plan if unmodifiable, unless custom rules exist
    $planId = $plan.Identity
    Write-Host " -> Processing Dial Plan: $planId" -ForegroundColor Cyan

    # Reconstruct ordered normalization rule objects in memory
    $RebuiltRules = [System.Collections.Generic.List[object]]::new()
    $OrderedBackupRules = $plan.NormalizationRules | Sort-Object Priority

    foreach ($r in $OrderedBackupRules) {
        $ruleObj = New-CsVoiceNormalizationRule `
            -Parent $planId `
            -Name $r.Name `
            -Description $r.Description `
            -Pattern $r.Pattern `
            -Translation $r.Translation `
            -IsInternalExtension ([bool]$r.IsInternalExtension) `
            -InMemory

        $RebuiltRules.Add($ruleObj)
    }

    # Check if Dial Plan currently exists in tenant
    $existingPlan = Get-CsTenantDialPlan -Identity $planId -ErrorAction SilentlyContinue

    if ($existingPlan) {
        if ($PSCmdlet.ShouldProcess($planId, "Overwrite existing Dial Plan and $($RebuiltRules.Count) Normalization Rules")) {
            Set-CsTenantDialPlan `
                -Identity $planId `
                -Description $plan.Description `
                -NormalizationRules ([array]$RebuiltRules)

            Write-Host "    [RESTORED] Overwrote '$planId' with $($RebuiltRules.Count) exact normalization rules." -ForegroundColor Green
        }
    } else {
        # Dial plan was deleted during the failed change—recreate it from scratch
        if ($planId -ne "Global" -and $PSCmdlet.ShouldProcess($planId, "Recreate deleted Dial Plan with $($RebuiltRules.Count) Normalization Rules")) {
            New-CsTenantDialPlan `
                -Identity $planId `
                -Description $plan.Description `
                -NormalizationRules ([array]$RebuiltRules)

            Write-Host "    [RECREATED] Restored deleted Dial Plan '$planId' with $($RebuiltRules.Count) rules." -ForegroundColor Green
        }
    }
}

# ------------------------------------------------------------------------------
# STEP 4: OPTIONAL USER ASSIGNMENT ROLLBACK
# ------------------------------------------------------------------------------
if ($RestoreUserAssignments -and $BackupData.UserAssignments.Count -gt 0) {
    Write-Host "`n[*] Restoring explicit user-level Dial Plan assignments..." -ForegroundColor Cyan

    foreach ($ua in $BackupData.UserAssignments) {
        if ($PSCmdlet.ShouldProcess($ua.UserPrincipalName, "Grant TenantDialPlan '$($ua.TenantDialPlan)'")) {
            Grant-CsTenantDialPlan -Identity $ua.UserPrincipalName -PolicyName $ua.TenantDialPlan
            Write-Host "    [GRANTED] $($ua.UserPrincipalName) -> $($ua.TenantDialPlan)" -ForegroundColor Green
        }
    }
}

$Stopwatch.Stop()
Write-Host "`n=======================================================" -ForegroundColor Green
Write-Host "[SUCCESS] Rollback completed in $([math]::Round($Stopwatch.Elapsed.TotalSeconds, 2)) seconds." -ForegroundColor Green
Write-Host "=======================================================" -ForegroundColor Green